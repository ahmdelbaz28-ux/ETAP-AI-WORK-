/**
 * MFASetup — Full TOTP setup flow with QR code display and verification.
 *
 * Flow:
 * 1. Call POST /api/v1/auth/mfa/totp/setup → get qr_code_uri
 * 2. Display QR code + manual secret key
 * 3. User scans QR with authenticator app
 * 4. User enters 6-digit TOTP code to verify
 * 5. Call POST /api/v1/auth/mfa/totp/verify → confirm setup
 *
 * Accessibility:
 * - QR code has `role="img"` with descriptive `aria-label`
 * - Manual key fallback with copy-to-clipboard
 * - Error announcements via `role="alert"` + `aria-live="assertive"`
 * - All inputs have `<label>` associations
 * - SR-only announcements for state changes
 */
export function MFASetup({ onComplete, onDismiss, authToken }: MFASetupProps) {
  const { t } = useTranslation();
  const { notify } = useNotify();

  // Setup state machine: "idle" → "loading" → "setup" → "verifying" → "done"
  const [step, setStep] = useState<"idle" | "loading" | "setup" | "verifying" | "done">("idle");
  const [qrUri, setQrUri] = useState("");
  const [secretKey, setSecretKey] = useState("");
  const [verifyError, setVerifyError] = useState<string | null>(null);

  // --- Step 1: Initiate TOTP setup ---
  const initiateSetup = useCallback(async () => {
    setStep("loading");
    try {
      const response = await fetch(`${API_BASE_URL}/api/v1/auth/mfa/totp/setup`, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${authToken}`,
          "Content-Type": "application/json",
        },
      });

      if (!response.ok) {
        const errData = await response.json().catch(() => ({}));
        throw new Error(errData.detail || errData.message || "MFA setup failed");
      }

      const data = await response.json();
      if (!data.success || !data.data?.qr_code_uri) {
        throw new Error("Invalid setup response");
      }

      setQrUri(data.data.qr_code_uri);
      // Extract secret from otpauth:// URI for manual entry fallback
      // Format: otpauth://totp/issuer:user?secret=BASE32&issuer=...
      try {
        const url = new URL(data.data.qr_code_uri);
        setSecretKey(url.searchParams.get("secret") || "");
      } catch {
        setSecretKey("");
      }

      setStep("setup");
    } catch (err) {
      const message = err instanceof Error ? err.message : "Setup failed";
      notify("error", message);
      setStep("idle");
    }
  }, [authToken, notify]);

  // --- Step 2: Verify TOTP code ---
  const verifyCode = useCallback(
    async (code: string) => {
      setStep("verifying");
      setVerifyError(null);
      try {
        const response = await fetch(`${API_BASE_URL}/api/v1/auth/mfa/totp/verify`, {
          method: "POST",
          headers: {
            Authorization: `Bearer ${authToken}`,
            "Content-Type": "application/json",
          },
          body: JSON.stringify({ code }),
        });

        if (!response.ok) {
          const errData = await response.json().catch(() => ({}));
          if (response.status === 429) {
            throw new Error("Too many failed attempts. Please wait before trying again.");
          }
          throw new Error(errData.message || errData.detail || "Invalid code");
        }

        const data = await response.json();
        if (data.success && data.data?.valid) {
          setStep("done");
          notify("success", t("mfa.setupComplete", "Two-factor authentication enabled!"));
          onComplete();
        } else {
          throw new Error("Verification failed");
        }
      } catch (err) {
        const message = err instanceof Error ? err.message : "Verification failed";
        setVerifyError(message);
        setStep("setup"); // Allow retry
      }
    },
    [authToken, notify, t, onComplete],
  );

  // Auto-initiate setup on mount
  useState(() => {
    if (step === "idle") initiateSetup();
  });

  return (
    <section
      className="w-full max-w-md mx-auto p-6 bg-slate-900/30 backdrop-blur-md border border-slate-800/40 rounded-2xl shadow-2xl"
      aria-label="Two-factor authentication setup"
    >
      {/* Header */}
      <div className="flex items-center justify-between mb-6">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-blue-500/10 flex items-center justify-center">
            <ShieldCheck className="w-5 h-5 text-blue-400" />
          </div>
          <div>
            <h3 className="text-lg font-bold text-white">
              {t("mfa.setupTitle", "Set Up 2FA")}
            </h3>
            <p className="text-xs text-slate-500">
              {t("mfa.setupSubtitle", "Secure your account with TOTP")}
            </p>
          </div>
        </div>
        <button
          type="button"
          onClick={onDismiss}
          className="p-1.5 rounded-lg hover:bg-slate-800 text-slate-400 hover:text-white transition-colors"
          aria-label="Dismiss two-factor authentication setup"
        >
          <X className="w-4 h-4" />
        </button>
      </div>

      {/* Step content */}
      <AnimatePresence mode="wait">
        {/* Loading */}
        {step === "loading" && (
          <motion.div
            key="loading"
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            className="flex flex-col items-center py-8 gap-3"
          >
            <Loader2 className="w-8 h-8 text-blue-400 animate-spin" />
            <p className="text-xs text-slate-400">Generating TOTP secret…</p>
          </motion.div>
        )}

        {/* QR Code Display */}
        {step === "setup" && (
          <motion.div
            key="setup"
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -10 }}
            className="space-y-6"
          >
            <QRCodeDisplay uri={qrUri} secretKey={secretKey} />
            <div className="border-t border-slate-800/40 pt-4">
              <p className="text-xs text-slate-400 mb-3">
                Enter the code from your authenticator app to complete setup:
              </p>
              <TOTPCodeInput onSubmit={verifyCode} loading={false} error={verifyError} />
            </div>
          </motion.div>
        )}

        {/* Verifying */}
        {step === "verifying" && (
          <motion.div
            key="verifying"
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            className="flex flex-col items-center py-8 gap-3"
          >
            <Loader2 className="w-8 h-8 text-blue-400 animate-spin" />
            <p className="text-xs text-slate-400">Verifying code…</p>
          </motion.div>
        )}

        {/* Done */}
        {step === "done" && (
          <motion.div
            key="done"
            initial={{ opacity: 0, scale: 0.95 }}
            animate={{ opacity: 1, scale: 1 }}
            exit={{ opacity: 0 }}
            className="flex flex-col items-center py-8 gap-3"
          >
            <CheckCircle className="w-12 h-12 text-green-400" />
            <p className="text-sm font-semibold text-green-400">
              {t("mfa.setupComplete", "Two-factor authentication enabled!")}
            </p>
            <p className="text-xs text-slate-500">
              Your account is now protected with 2FA.
            </p>
          </motion.div>
        )}
      </AnimatePresence>

      {/* SR-only live region for state announcements */}
      <div aria-live="polite" className="sr-only">
        {step === "loading" && "Loading two-factor authentication setup."}
        {step === "setup" && "QR code displayed. Scan with your authenticator app or enter the secret key manually."}
        {step === "verifying" && "Verifying authentication code."}
        {step === "done" && "Two-factor authentication has been successfully enabled."}
      </div>
    </section>
  );
}
