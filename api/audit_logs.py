@router.get("/", response_model=AuditLogListResponse, summary="List audit logs")
async def list_audit_logs(
    page: int = Query(default=1, ge=1, description="1-based page number"),
    page_size: int = Query(default=20, ge=1, le=100, description="Items per page"),
    severity: Optional[str] = Query(default=None, description="Filter by severity level"),
    action: Optional[str] = Query(default=None, description="Filter by action type"),
    user: Optional[str] = Query(default=None, description="Filter by username"),
    start_date: Optional[str] = Query(default=None, description="Start date (ISO-8601)"),
    end_date: Optional[str] = Query(default=None, description="End date (ISO-8601)"),
    search: Optional[str] = Query(default=None, description="Search in details field"),
) -> AuditLogListResponse:
    """List audit log entries with search, filter, and pagination support.

    Supports filtering by **severity**, **action**, **user**, **date range**
    (``start_date`` / ``end_date``), and free-text **search** across the
    ``details`` field.

    Results are sorted by timestamp descending (newest first).
    """
    source_logs = _SAMPLE_AUDIT_LOGS
    try:
        from fireai.core.audit_store import AuditStore

        real_events = AuditStore.get_events()
        if real_events:
            source_logs = real_events
    except Exception:
        pass

    filtered = _apply_filters(
        source_logs,
        severity=severity,
        action=action,
        user=user,
        start_date=start_date,
        end_date=end_date,
        search=search,
    )

    total = len(filtered)
    total_pages = max(1, math.ceil(total / page_size))
    offset = (page - 1) * page_size
    page_entries = filtered[offset : offset + page_size]

    return AuditLogListResponse(
        entries=[AuditLogEntry(**e) for e in page_entries],
        total=total,
        page=page,
        page_size=page_size,
        total_pages=total_pages,
    )


@router.get(
    "/export/csv",
    summary="Export audit logs as CSV",
    response_class=StreamingResponse,
)
async def export_audit_logs_csv(
    severity: Optional[str] = Query(default=None, description="Filter by severity level"),
    action: Optional[str] = Query(default=None, description="Filter by action type"),
    user: Optional[str] = Query(default=None, description="Filter by username"),
    start_date: Optional[str] = Query(default=None, description="Start date (ISO-8601)"),
    end_date: Optional[str] = Query(default=None, description="End date (ISO-8601)"),
    search: Optional[str] = Query(default=None, description="Search in details field"),
) -> StreamingResponse:
    """Export filtered audit log entries as a CSV file download.

    Accepts the same filter parameters as the list endpoint.  Returns a
    ``text/csv`` streaming response with a ``Content-Disposition`` header
    so the browser triggers a file download.

    .. note::

        This endpoint MUST be registered before ``/{log_id}`` to avoid
        FastAPI matching ``"export"`` as a path parameter.
    """
    filtered = _apply_filters(
        _SAMPLE_AUDIT_LOGS,
        severity=severity,
        action=action,
        user=user,
        start_date=start_date,
        end_date=end_date,
        search=search,
    )

    output = io.StringIO()
    writer = csv.DictWriter(
        output,
        fieldnames=[
            "id",
            "timestamp",
            "severity",
            "action",
            "user",
            "ip_address",
            "resource",
            "details",
            "trace_id",
        ],
    )
    writer.writeheader()
    for row in filtered:
        writer.writerow(row)

    output.seek(0)
    filename = f"audit-logs-{datetime.now(UTC).strftime('%Y%m%dT%H%M%SZ')}.csv"
    return StreamingResponse(
        iter([output.getvalue()]),
        media_type="text/csv",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


@router.get("/stats", response_model=AuditLogStats, summary="Get audit log statistics")
async def get_audit_log_stats() -> AuditLogStats:
    """Return aggregate statistics for audit log entries.

    Returns:
        - **total**: Total number of entries.
        - **by_severity**: Entry counts grouped by severity level.
        - **by_action**: Entry counts grouped by action type.
        - **recent_trends**: Daily entry counts for the last 7 days.
    """
    source_logs = _SAMPLE_AUDIT_LOGS
    try:
        from fireai.core.audit_store import AuditStore

        real_events = AuditStore.get_events()
        if real_events:
            source_logs = real_events
    except Exception:
        pass

    # Count by severity
    severity_counts: dict[str, int] = {}
    for entry in source_logs:
        sev = entry.get("severity", "info")
        severity_counts[sev] = severity_counts.get(sev, 0) + 1

    # Count by action
    action_counts: dict[str, int] = {}
    for entry in source_logs:
        act = entry.get("action", "unknown")
        action_counts[act] = action_counts.get(act, 0) + 1

    # Recent trends — last 7 days
    # For demo data we build a trend from the timestamps present.
    trends: dict[str, int] = {}
    for i in range(7):
        day = (_NOW - timedelta(days=i)).strftime("%Y-%m-%d")
        trends[day] = 0

    for entry in source_logs:
        try:
            day = datetime.fromisoformat(entry["timestamp"]).strftime("%Y-%m-%d")
        except (ValueError, KeyError):
            continue
        if day in trends:
            trends[day] += 1

    # Sort severity counts by a canonical order
    _SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
    by_severity = sorted(
        [SeverityCount(severity=k, count=v) for k, v in severity_counts.items()],
        key=lambda x: _SEV_ORDER.get(x.severity, 99),
    )

    # Sort action counts by count descending
    by_action = sorted(
        [ActionCount(action=k, count=v) for k, v in action_counts.items()],
        key=lambda x: x.count,
        reverse=True,
    )

    # Sort trends by date ascending
    recent_trends = sorted(
        [TrendPoint(date=k, count=v) for k, v in trends.items()],
        key=lambda x: x.date,
    )

    return AuditLogStats(
        total=len(_SAMPLE_AUDIT_LOGS),
        by_severity=by_severity,
        by_action=by_action,
        recent_trends=recent_trends,
    )


@router.get(
    "/{log_id}",
    response_model=AuditLogEntry,
    summary="Get a specific audit log entry",
)
async def get_audit_log(log_id: str) -> AuditLogEntry:
    """Retrieve a single audit log entry by its unique ID.

    .. note::

        This endpoint is registered AFTER ``/export/csv`` and ``/stats``
        to avoid FastAPI matching ``"export"`` or ``"stats"`` as a
        ``log_id`` path parameter.

    Raises:
        404: If no entry with the given ``log_id`` exists.
    """
    for entry in _SAMPLE_AUDIT_LOGS:
        if entry["id"] == log_id:
            return AuditLogEntry(**entry)
    raise HTTPException(
        status_code=status.HTTP_404_NOT_FOUND,
        detail=f"Audit log entry '{log_id}' not found.",
    )
