"""
api/audit_logs.py — Security Audit Log API endpoint.

Provides a REST API for querying, filtering, and exporting security audit
log entries generated by the :mod:`api.security_audit` module.

Endpoints
---------

* ``GET /``              — List audit logs with search, filter, and pagination
* ``GET /{log_id}``      — Retrieve a single audit log entry by ID
* ``GET /export/csv``    — Export filtered audit logs as CSV
* ``GET /stats``         — Aggregate statistics (count by severity, action, trends)

All endpoints require the ``X-API-Key`` header (validated via
:func:`api.dependencies.get_api_key`).

Pydantic models
---------------

* :class:`AuditLogEntry`       — Single audit log record
* :class:`AuditLogFilter`      — Filter criteria for list queries
* :class:`AuditLogListResponse`— Paginated list response
* :class:`AuditLogExportRequest`— Export request body (future POST support)
"""

