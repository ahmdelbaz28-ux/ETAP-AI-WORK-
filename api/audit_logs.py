def _apply_filters(
    entries: list[dict[str, Any]],
    severity: Optional[str] = None,
    action: Optional[str] = None,
    user: Optional[str] = None,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    search: Optional[str] = None,
) -> list[dict[str, Any]]:
    """Apply filter criteria to a list of audit log dicts.

    Args:
        entries: The full list of audit log dictionaries.
        severity: Filter by severity (case-insensitive match).
        action: Filter by action type (case-insensitive match).
        user: Filter by username (case-insensitive partial match).
        start_date: ISO-8601 datetime — include entries >= this timestamp.
        end_date: ISO-8601 datetime — include entries <= this timestamp.
        search: Free-text search across the ``details`` field (case-insensitive).

    Returns:
        Filtered list of audit log dictionaries.
    """
    result = entries

    if severity is not None:
        sev_lower = severity.lower()
        result = [e for e in result if e["severity"].lower() == sev_lower]

    if action is not None:
        act_lower = action.lower()
        result = [e for e in result if e["action"].lower() == act_lower]

    if user is not None:
        user_lower = user.lower()
        result = [e for e in result if user_lower in e["user"].lower()]

    if start_date is not None:
        try:
            start_dt = datetime.fromisoformat(start_date)
        except ValueError:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f"Invalid start_date format: {start_date!r}. Expected ISO-8601.",
            ) from None
        result = [e for e in result if datetime.fromisoformat(e["timestamp"]) >= start_dt]

    if end_date is not None:
        try:
            end_dt = datetime.fromisoformat(end_date)
        except ValueError:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f"Invalid end_date format: {end_date!r}. Expected ISO-8601.",
            ) from None
        result = [e for e in result if datetime.fromisoformat(e["timestamp"]) <= end_dt]

    if search is not None:
        search_lower = search.lower()
        result = [e for e in result if search_lower in e["details"].lower()]

    return result


