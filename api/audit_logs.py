class AuditLogEntry(BaseModel):
    """A single security audit log entry.

    Attributes:
        id: Unique identifier for the log entry.
        timestamp: ISO-8601 UTC timestamp when the event occurred.
        severity: Severity level (critical / high / medium / low / info).
        action: The action that was audited (e.g. ``login_success``).
        user: Username or service account that performed the action.
        ip_address: Client IP address associated with the event.
        resource: The resource or endpoint that was accessed.
        details: Free-text description of the event.
        trace_id: Distributed tracing correlation ID.
    """

    model_config = ConfigDict(frozen=True)

    id: str
    timestamp: str
    severity: str
    action: str
    user: str
    ip_address: str
    resource: str
    details: str
    trace_id: str


class AuditLogFilter(BaseModel):
    """Filter criteria for audit log list queries.

    All fields are optional — only provided fields are applied.

    Attributes:
        severity: Filter by severity level.
        action: Filter by action type.
        user: Filter by username.
        start_date: Include entries on or after this ISO-8601 date.
        end_date: Include entries on or before this ISO-8601 date.
        search: Free-text search across the ``details`` field.
    """

    model_config = ConfigDict(frozen=True)

    severity: Optional[str] = Field(default=None, description="Filter by severity level")
    action: Optional[str] = Field(default=None, description="Filter by action type")
    user: Optional[str] = Field(default=None, description="Filter by username")
    start_date: Optional[str] = Field(default=None, description="Start date (ISO-8601)")
    end_date: Optional[str] = Field(default=None, description="End date (ISO-8601)")
    search: Optional[str] = Field(default=None, description="Search in details field")


class AuditLogListResponse(BaseModel):
    """Paginated response for audit log list queries.

    Attributes:
        entries: List of audit log entries for the current page.
        total: Total number of entries matching the filter.
        page: Current page number (1-based).
        page_size: Number of entries per page.
        total_pages: Total number of pages.
    """

    entries: list[AuditLogEntry]
    total: int
    page: int
    page_size: int
    total_pages: int


class AuditLogExportRequest(BaseModel):
    """Request body for audit log export.

    Attributes:
        format: Export format — ``csv`` or ``pdf``.
        filters: Optional filter criteria to apply before exporting.
    """

    format: str = Field(
        default="csv", pattern=r"^(csv|pdf)$", description="Export format: csv or pdf"
    )
    filters: Optional[AuditLogFilter] = Field(default=None, description="Filter criteria")


